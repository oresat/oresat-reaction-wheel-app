def write_outputs(outdir: Path, aggregate: pd.DataFrame, per_run: pd.DataFrame, run_summary: pd.DataFrame, plot_df: pd.DataFrame, plot_summary: pd.DataFrame, settings: pd.DataFrame):
    outdir.mkdir(parents=True, exist_ok=True)
    paths = {
        "aggregate_all": outdir / "torque_speed_aggregate_all.csv",
        "aggregate_runs": outdir / "torque_speed_aggregate_runs.csv",
        "aggregate_summary": outdir / "torque_speed_aggregate_summary.csv",
        "plot_data": outdir / "torque_speed_plot_data.csv",
        "plot_summary": outdir / "torque_speed_plot_summary.csv",
        "settings": outdir / "torque_speed_processing_settings.csv",
    }
    aggregate.to_csv(paths["aggregate_all"], index=False)
    per_run.to_csv(paths["aggregate_runs"], index=False)
    run_summary.to_csv(paths["aggregate_summary"], index=False)
    plot_df.to_csv(paths["plot_data"], index=False)
    plot_summary.to_csv(paths["plot_summary"], index=False)
    settings.to_csv(paths["settings"], index=False)
    for path in paths.values():
        print(f"[CSV] {path}")
    if not aggregate.empty:
        for strategy, g in aggregate.groupby("strategy"):
            safe = strategy.lower().replace(" ", "_")
            path = outdir / f"torque_speed_aggregate_{safe}.csv"
            g.to_csv(path, index=False)
            print(f"[CSV] {path}")


