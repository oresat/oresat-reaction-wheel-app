def collect_speed_time_data(jobs: list[dict]) -> pd.DataFrame:
    """
    Load the ramp portion of every raw run and align each run at the beginning
    of TEST_STATE_RAMP. This keeps the speed-versus-time comparison independent
    of the torque filtering and RPM binning pipeline.
    """
    frames = []

    for job in jobs:
        df = read_csv_checked(job["path"]).copy()

        if "omega_rpm" not in df.columns:
            continue

        if "test_state" in df.columns:
            ramp_mask = (
                pd.to_numeric(df["test_state"], errors="coerce")
                .round()
                .astype("Int64")
                == TORQUE_SPEED_RAMP_STATE
            )
            ramp = df.loc[ramp_mask].copy()
        else:
            ramp = df.copy()

        ramp["host_time_s"] = pd.to_numeric(ramp["host_time_s"], errors="coerce")
        ramp["omega_rpm"] = pd.to_numeric(ramp["omega_rpm"], errors="coerce")

        if "speed_command_rpm" in ramp.columns:
            ramp["speed_command_rpm"] = pd.to_numeric(
                ramp["speed_command_rpm"], errors="coerce"
            )
        else:
            ramp["speed_command_rpm"] = np.nan

        ramp = ramp[
            np.isfinite(ramp["host_time_s"]) &
            np.isfinite(ramp["omega_rpm"])
        ].sort_values("host_time_s")

        if ramp.empty:
            continue

        t0 = float(ramp["host_time_s"].iloc[0])
        ramp["time_from_ramp_start_s"] = ramp["host_time_s"] - t0
        ramp["strategy"] = job["strategy"]
        ramp["run_index"] = job["run_index"]
        ramp["run_id"] = f"{job['strategy']}_run{job['run_index']}"
        ramp["source_file"] = str(job["path"])

        frames.append(
            ramp[
                [
                    "strategy",
                    "run_index",
                    "run_id",
                    "source_file",
                    "time_from_ramp_start_s",
                    "omega_rpm",
                    "speed_command_rpm",
                ]
            ]
        )

    return pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()


def aggregate_speed_time(raw_speed: pd.DataFrame, grid_period_s: float = 0.05) -> pd.DataFrame:
    """
    Interpolate every run onto a shared time grid, then compute the mean and
    standard deviation for each commutation strategy.
    """
    if raw_speed.empty:
        return pd.DataFrame()

    interpolated_runs = []

    for (strategy, run_id), g in raw_speed.groupby(["strategy", "run_id"]):
        g = g.sort_values("time_from_ramp_start_s")

        t = pd.to_numeric(
            g["time_from_ramp_start_s"], errors="coerce"
        ).to_numpy(dtype=float)
        omega = pd.to_numeric(g["omega_rpm"], errors="coerce").to_numpy(dtype=float)
        command = pd.to_numeric(
            g["speed_command_rpm"], errors="coerce"
        ).to_numpy(dtype=float)

        valid_omega = np.isfinite(t) & np.isfinite(omega)
        if np.sum(valid_omega) < 2:
            continue

        t_end = float(np.nanmax(t[valid_omega]))
        grid = np.arange(0.0, t_end + 0.5 * grid_period_s, grid_period_s)

        omega_i = np.interp(grid, t[valid_omega], omega[valid_omega])

        valid_command = np.isfinite(t) & np.isfinite(command)
        if np.sum(valid_command) >= 2:
            command_i = np.interp(grid, t[valid_command], command[valid_command])
        else:
            command_i = np.full_like(grid, np.nan, dtype=float)

        interpolated_runs.append(
            pd.DataFrame(
                {
                    "strategy": strategy,
                    "run_id": run_id,
                    "time_from_ramp_start_s": grid,
                    "omega_rpm": omega_i,
                    "speed_command_rpm": command_i,
                }
            )
        )

    if not interpolated_runs:
        return pd.DataFrame()

    all_runs = pd.concat(interpolated_runs, ignore_index=True)
    rows = []

    for (strategy, time_s), g in all_runs.groupby(
        ["strategy", "time_from_ramp_start_s"]
    ):
        omega = pd.to_numeric(g["omega_rpm"], errors="coerce").to_numpy(dtype=float)
        command = pd.to_numeric(
            g["speed_command_rpm"], errors="coerce"
        ).to_numpy(dtype=float)

        omega = omega[np.isfinite(omega)]
        command = command[np.isfinite(command)]

        if len(omega) == 0:
            continue

        rows.append(
            {
                "strategy": strategy,
                "time_from_ramp_start_s": float(time_s),
                "run_count": int(g["run_id"].nunique()),
                "omega_mean_rpm": float(np.nanmean(omega)),
                "omega_std_rpm": (
                    float(np.nanstd(omega, ddof=1)) if len(omega) > 1 else 0.0
                ),
                "speed_command_mean_rpm": (
                    float(np.nanmean(command)) if len(command) else np.nan
                ),
            }
        )

    return (
        pd.DataFrame(rows)
        .sort_values(["strategy", "time_from_ramp_start_s"])
        .reset_index(drop=True)
    )


def plot_speed_vs_time(
    raw_speed: pd.DataFrame,
    aggregate_speed: pd.DataFrame,
    outdir: Path,
    show_std: bool,
):
    if aggregate_speed.empty:
        return

    fig, ax = setup_axes(
        "Wheel Speed During Torque-Speed Ramp",
        "Time From Ramp Start (s)",
        "Wheel Speed (RPM)",
    )

    # Light individual-run traces show repeatability without dominating the plot.
    for (strategy, run_id), g in raw_speed.groupby(["strategy", "run_id"]):
        g = g.sort_values("time_from_ramp_start_s")
        ax.plot(
            g["time_from_ramp_start_s"],
            g["omega_rpm"],
            linewidth=0.6,
            alpha=0.10,
            color=STRATEGY_COLORS[strategy],
        )

    available = list(aggregate_speed["strategy"].dropna().unique())
    ordered = [s for s in STRATEGY_ORDER if s in available]
    ordered += [s for s in available if s not in ordered]

    for strategy in ordered:
        g = (
            aggregate_speed[aggregate_speed["strategy"] == strategy]
            .sort_values("time_from_ramp_start_s")
        )

        if g.empty:
            continue

        x = g["time_from_ramp_start_s"].to_numpy(dtype=float)
        y = g["omega_mean_rpm"].to_numpy(dtype=float)

        ax.plot(
            x,
            y,
            linewidth=2.2,
            label=f"{strategy} measured",
            color=STRATEGY_COLORS[strategy],
        )

        if show_std:
            std = g["omega_std_rpm"].to_numpy(dtype=float)
            ax.fill_between(
                x,
                y - std,
                y + std,
                color=STRATEGY_COLORS[strategy],
                alpha=0.15,
                linewidth=0.0,
            )

        command = pd.to_numeric(
            g["speed_command_mean_rpm"],
            errors="coerce",
        ).to_numpy(dtype=float)

        if np.isfinite(command).any():
            ax.plot(
                x,
                command,
                linewidth=1.2,
                linestyle="--",
                alpha=0.7,
                label=f"{strategy} command",
                color=STRATEGY_COLORS[strategy],
            )

    ax.legend()
    save_figure(fig, outdir, "torque_speed_wheel_speed_vs_time")


