def main():
    parser = argparse.ArgumentParser(description="Process, aggregate, and plot OreSat torque-speed CSVs.")
    parser.add_argument("--trap", nargs="+", help="One or more trapezoidal torque-speed CSVs")
    parser.add_argument("--sine", nargs="+", help="One or more sinusoidal torque-speed CSVs")
    parser.add_argument("--foc", nargs="+", help="One or more FOC torque-speed CSVs")
    parser.add_argument("--outdir", default=DEFAULT_OUTDIR)
    parser.add_argument("--bin-width-rpm", type=float, default=DEFAULT_BIN_WIDTH_RPM)
    parser.add_argument("--min-samples-per-bin", type=int, default=DEFAULT_MIN_SAMPLES_PER_BIN)
    parser.add_argument("--use-bin-mean", action="store_true")
    parser.add_argument("--min-speed-rpm", type=float, default=0.0)
    parser.add_argument("--max-speed-rpm", type=float, default=None)
    parser.add_argument("--include-ramp-down", action="store_true")
    parser.add_argument("--signed-torque", action="store_true")
    parser.add_argument("--no-spike-rejection", action="store_true")
    parser.add_argument("--max-torque-slew-mnm-s", type=float, default=DEFAULT_MAX_TORQUE_SLEW_MNM_S)
    parser.add_argument("--hampel-window-s", type=float, default=DEFAULT_HAMPEL_WINDOW_S)
    parser.add_argument("--hampel-n-sigma", type=float, default=DEFAULT_HAMPEL_N_SIGMA)
    parser.add_argument("--mean-window-s", type=float, default=DEFAULT_MEAN_WINDOW_S)
    parser.add_argument("--final-bin-smooth-window", type=int, default=DEFAULT_FINAL_BIN_SMOOTH_WINDOW)
    parser.add_argument("--no-final-bin-smoothing", action="store_true")
    parser.add_argument(
        "--no-show-std",
        action="store_true",
        help="Disable the default +/- one-standard-deviation bands.",
    )
    parser.add_argument("--skip-normalized", action="store_true")
    parser.add_argument("--plot-column", default=DEFAULT_PLOT_COLUMN)
    args = parser.parse_args()

    if args.bin_width_rpm <= 0.0:
        raise ValueError("--bin-width-rpm must be positive.")
    if args.final_bin_smooth_window <= 0:
        raise ValueError("--final-bin-smooth-window must be positive.")

    jobs = collect_inputs(args)
    print("[INPUT] Processing raw CSVs:")
    for job in jobs:
        print(f"  {job['strategy']} run {job['run_index']}: {job['path']}")

    per_run_frames = []
    summary_rows = []
    for job in jobs:
        binned, summary = process_one_run(job, args)
        if not binned.empty:
            per_run_frames.append(binned)
        summary_rows.append(summary)
        print(
            f"[RUN] {summary['strategy']} run {summary['run_index']}: "
            f"filtered={summary['filtered_rows_used']} "
            f"binned={summary['binned_points']} "
            f"rejected={summary['rejected_samples']} ({summary['rejected_percent']:.2f}%) "
            f"status={summary['final_status']} fault={summary['fault_code']}"
        )

    per_run = pd.concat(per_run_frames, ignore_index=True) if per_run_frames else pd.DataFrame()
    run_summary = pd.DataFrame(summary_rows)
    aggregate = aggregate_runs(per_run)
    aggregate = apply_final_bin_smoothing(
        aggregate=aggregate,
        smooth_window=args.final_bin_smooth_window,
        enable=not args.no_final_bin_smoothing,
    )
    plot_df = prepare_plot_data(aggregate, args.plot_column)

    outdir = Path(args.outdir)

    speed_time_raw = collect_speed_time_data(jobs)
    speed_time_aggregate = aggregate_speed_time(speed_time_raw)
    plot_speed_vs_time(
        raw_speed=speed_time_raw,
        aggregate_speed=speed_time_aggregate,
        outdir=outdir,
        show_std=not args.no_show_std,
    )

    if not speed_time_raw.empty:
        speed_time_raw.to_csv(
            outdir / "torque_speed_wheel_speed_vs_time_runs.csv",
            index=False,
        )
    if not speed_time_aggregate.empty:
        speed_time_aggregate.to_csv(
            outdir / "torque_speed_wheel_speed_vs_time_aggregate.csv",
            index=False,
        )

    plot_measured_torque_speed(plot_df, outdir, not args.no_show_std, args.signed_torque)
    if not args.skip_normalized:
        plot_normalized_torque_speed(plot_df, outdir, not args.no_show_std, args.signed_torque)

    plot_summary = make_plot_summary(plot_df)
    settings = processing_settings_table(args)
    write_outputs(outdir, aggregate, per_run, run_summary, plot_df, plot_summary, settings)
    print("[DONE] Torque-speed processing, aggregation, and plotting complete.")


if __name__ == "__main__":
    main()