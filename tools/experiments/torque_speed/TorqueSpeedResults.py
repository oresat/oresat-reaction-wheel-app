def reject_slew_spikes(values: pd.Series, time_s: pd.Series, max_slew_mnm_s: float, passes: int = 2) -> tuple[pd.Series, pd.Series]:
    y_original = pd.to_numeric(values, errors="coerce").astype(float)
    t = pd.to_numeric(time_s, errors="coerce").astype(float)

    if not np.isfinite(max_slew_mnm_s) or max_slew_mnm_s <= 0.0:
        flags = pd.Series(False, index=y_original.index)
        return y_original, flags

    max_slew_nm_s = max_slew_mnm_s / 1000.0
    y = y_original.copy()
    flags_total = pd.Series(False, index=y.index)

    for _ in range(max(1, passes)):
        y_work = y.copy()
        flags = pd.Series(False, index=y.index)
        last_t = None
        last_y = None

        for idx in y.index:
            yi = y.loc[idx]
            ti = t.loc[idx]
            if not np.isfinite(yi) or not np.isfinite(ti):
                continue
            if last_t is None:
                last_t = ti
                last_y = yi
                continue
            dt = ti - last_t
            if not np.isfinite(dt) or dt <= 0.0:
                last_t = ti
                last_y = yi
                continue
            allowed_jump = max_slew_nm_s * dt
            actual_jump = abs(yi - last_y)
            if actual_jump > allowed_jump:
                flags.loc[idx] = True
                y_work.loc[idx] = np.nan
                continue
            last_t = ti
            last_y = yi

        flags_total |= flags
        y = y_work.interpolate(limit_direction="both").bfill().ffill()

    return y, flags_total


def hampel_filter(values: pd.Series, dt_s: float, window_s: float, n_sigma: float) -> tuple[pd.Series, pd.Series]:
    y = pd.to_numeric(values, errors="coerce").astype(float)
    window_n = make_odd(window_seconds_to_samples(window_s, dt_s))
    if window_n <= 1:
        flags = pd.Series(False, index=y.index)
        return y, flags

    local_median = y.rolling(window=window_n, center=True, min_periods=max(1, window_n // 3)).median()
    abs_dev = (y - local_median).abs()
    local_mad = abs_dev.rolling(window=window_n, center=True, min_periods=max(1, window_n // 3)).median()
    robust_sigma = 1.4826 * local_mad
    threshold = n_sigma * robust_sigma
    flags = (abs_dev > threshold) & np.isfinite(abs_dev) & np.isfinite(threshold) & (threshold > 0.0)

    cleaned = y.copy()
    cleaned.loc[flags] = local_median.loc[flags]
    cleaned = cleaned.interpolate(limit_direction="both").bfill().ffill()

    return cleaned, flags


def rolling_mean(values: pd.Series, dt_s: float, window_s: float) -> pd.Series:
    y = pd.to_numeric(values, errors="coerce").astype(float)
    window_n = make_odd(window_seconds_to_samples(window_s, dt_s))
    if window_n <= 1:
        return y
    y = y.rolling(window=window_n, center=True, min_periods=max(1, window_n // 3)).mean()
    return y.interpolate(limit_direction="both").bfill().ffill()


def process_torque_signal(df: pd.DataFrame, enable_spike_rejection: bool, max_torque_slew_mnm_s: float, hampel_window_s: float, hampel_n_sigma: float, mean_window_s: float) -> pd.DataFrame:
    out = df.copy()
    dt_s = estimate_sample_period_s(out)
    raw = pd.to_numeric(out["torque_Nm"], errors="coerce").astype(float)
    out["torque_raw_Nm"] = raw

    if enable_spike_rejection:
        slew_clean, slew_flags = reject_slew_spikes(raw, out["host_time_s"], max_torque_slew_mnm_s, passes=2)
    else:
        slew_clean = raw
        slew_flags = pd.Series(False, index=out.index)

    out["torque_slew_clean_Nm"] = slew_clean
    out["torque_slew_spike_flag"] = slew_flags.astype(int)

    if enable_spike_rejection:
        hampel_clean, hampel_flags = hampel_filter(slew_clean, dt_s, hampel_window_s, hampel_n_sigma)
    else:
        hampel_clean = slew_clean
        hampel_flags = pd.Series(False, index=out.index)

    out["torque_hampel_clean_Nm"] = hampel_clean
    out["torque_hampel_spike_flag"] = hampel_flags.astype(int)
    out["torque_smoothed_Nm"] = rolling_mean(hampel_clean, dt_s, mean_window_s)
    out["torque_rejected_flag"] = ((out["torque_slew_spike_flag"] > 0) | (out["torque_hampel_spike_flag"] > 0)).astype(int)

    return out


