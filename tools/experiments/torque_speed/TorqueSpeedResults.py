def aggregate_runs(per_run: pd.DataFrame) -> pd.DataFrame:
    if per_run.empty:
        return pd.DataFrame()

    group_cols = ["strategy", "speed_bin_center_rpm", "speed_bin_low_rpm", "speed_bin_high_rpm"]
    rows = []
    for keys, g in per_run.groupby(group_cols, dropna=False):
        strategy, center, low, high = keys
        values = pd.to_numeric(g["torque_run_value_Nm"], errors="coerce").to_numpy(dtype=float)
        values = values[np.isfinite(values)]
        sample_counts = pd.to_numeric(g["sample_count"], errors="coerce").to_numpy(dtype=float)
        sample_counts = sample_counts[np.isfinite(sample_counts)]
        if len(values) == 0:
            continue

        std_nm = float(np.nanstd(values, ddof=1)) if len(values) > 1 else 0.0
        mean_nm = float(np.nanmean(values))
        median_nm = float(np.nanmedian(values))
        iqr_nm = iqr(values)
        rows.append({
            "strategy": strategy,
            "speed_bin_center_rpm": center,
            "speed_bin_low_rpm": low,
            "speed_bin_high_rpm": high,
            "run_count": int(g["run_id"].nunique()),
            "total_sample_count": int(np.nansum(sample_counts)) if len(sample_counts) else 0,
            "torque_mean_Nm": mean_nm,
            "torque_median_Nm": median_nm,
            "torque_std_Nm": std_nm,
            "torque_min_Nm": float(np.nanmin(values)),
            "torque_max_Nm": float(np.nanmax(values)),
            "torque_iqr_Nm": iqr_nm,
            "torque_mean_mNm": mean_nm * 1000.0,
            "torque_median_mNm": median_nm * 1000.0,
            "torque_std_mNm": std_nm * 1000.0,
            "torque_iqr_mNm": iqr_nm * 1000.0 if np.isfinite(iqr_nm) else np.nan,
        })

    out = pd.DataFrame(rows)
    return out.sort_values(["strategy", "speed_bin_center_rpm"]).reset_index(drop=True)


def apply_final_bin_smoothing(aggregate: pd.DataFrame, smooth_window: int, enable: bool) -> pd.DataFrame:
    if aggregate.empty:
        return aggregate

    out = aggregate.copy()
    for col in ["torque_mean_Nm", "torque_median_Nm", "torque_mean_mNm", "torque_median_mNm"]:
        filtered_col = col.replace("_Nm", "_filtered_Nm").replace("_mNm", "_filtered_mNm")
        out[filtered_col] = np.nan

    for strategy, idx in out.groupby("strategy").groups.items():
        g = out.loc[idx].sort_values("speed_bin_center_rpm")
        sorted_idx = g.index
        if enable:
            out.loc[sorted_idx, "torque_mean_filtered_Nm"] = rolling_centered(g["torque_mean_Nm"], smooth_window, use_median=False).to_numpy()
            out.loc[sorted_idx, "torque_median_filtered_Nm"] = rolling_centered(g["torque_median_Nm"], smooth_window, use_median=False).to_numpy()
            out.loc[sorted_idx, "torque_mean_filtered_mNm"] = out.loc[sorted_idx, "torque_mean_filtered_Nm"] * 1000.0
            out.loc[sorted_idx, "torque_median_filtered_mNm"] = out.loc[sorted_idx, "torque_median_filtered_Nm"] * 1000.0
        else:
            out.loc[sorted_idx, "torque_mean_filtered_Nm"] = g["torque_mean_Nm"].to_numpy()
            out.loc[sorted_idx, "torque_median_filtered_Nm"] = g["torque_median_Nm"].to_numpy()
            out.loc[sorted_idx, "torque_mean_filtered_mNm"] = g["torque_mean_mNm"].to_numpy()
            out.loc[sorted_idx, "torque_median_filtered_mNm"] = g["torque_median_mNm"].to_numpy()

    # ------------------------------------------------------------------
    # Zero the final torque curves so every strategy starts at 0 Nm.
    # Uses the median torque below 500 RPM.
    # ------------------------------------------------------------------

    for strategy, idx in out.groupby("strategy").groups.items():

        g = out.loc[idx]

        baseline_mask = g["speed_bin_center_rpm"] <= DEFAULT_ZERO_REFERENCE_MAX_RPM

        if baseline_mask.any():
            baseline = np.nanmedian(
                g.loc[baseline_mask, "torque_median_filtered_Nm"]
            )
        else:
            baseline = 0.0

        out.loc[idx, "torque_median_filtered_Nm"] -= baseline
        out.loc[idx, "torque_mean_filtered_Nm"]   -= baseline

        out.loc[idx, "torque_median_filtered_mNm"] = (
            out.loc[idx, "torque_median_filtered_Nm"] * 1000.0
        )

        out.loc[idx, "torque_mean_filtered_mNm"] = (
            out.loc[idx, "torque_mean_filtered_Nm"] * 1000.0
        )

    return out


