def filter_torque_speed_data(df: pd.DataFrame, use_ramp_only: bool, min_speed_rpm: float, max_speed_rpm: float, torque_abs: bool, enable_spike_rejection: bool, max_torque_slew_mnm_s: float, hampel_window_s: float, hampel_n_sigma: float, mean_window_s: float) -> pd.DataFrame:
    out = df.copy()
    if use_ramp_only and "test_state" in out.columns:
        out = out[out["test_state"].round().astype("Int64") == TORQUE_SPEED_RAMP_STATE]

    out = out[np.isfinite(out["torque_speed_abs_rpm"])]
    out = out[np.isfinite(out["torque_Nm"])]
    out = out[out["torque_speed_abs_rpm"] >= min_speed_rpm]
    if max_speed_rpm is not None:
        out = out[out["torque_speed_abs_rpm"] <= max_speed_rpm]

    out = out.sort_values("host_time_s").reset_index(drop=True)
    out = process_torque_signal(out, enable_spike_rejection, max_torque_slew_mnm_s, hampel_window_s, hampel_n_sigma, mean_window_s)
    out["torque_plot_Nm"] = np.abs(out["torque_smoothed_Nm"]) if torque_abs else out["torque_smoothed_Nm"]
    return out[np.isfinite(out["torque_plot_Nm"])].copy()


def bin_one_run(df: pd.DataFrame, bin_width_rpm: float, min_samples_per_bin: int, use_median: bool) -> pd.DataFrame:
    if df.empty:
        return pd.DataFrame()

    speed = df["torque_speed_abs_rpm"].to_numpy(dtype=float)
    torque = df["torque_plot_Nm"].to_numpy(dtype=float)
    max_speed = np.nanmax(speed)
    if not np.isfinite(max_speed):
        max_speed = 0.0

    upper = np.ceil(max_speed / bin_width_rpm) * bin_width_rpm
    bins = np.arange(0.0, upper + bin_width_rpm, bin_width_rpm)
    if len(bins) < 2:
        bins = np.array([0.0, bin_width_rpm])

    bin_index = np.digitize(speed, bins) - 1
    rows = []
    for i in range(len(bins) - 1):
        mask = bin_index == i
        n = int(np.sum(mask))
        if n < min_samples_per_bin:
            continue
        torque_bin = torque[mask]
        mean = float(np.nanmean(torque_bin))
        median = float(np.nanmedian(torque_bin))
        rows.append({
            "speed_bin_center_rpm": 0.5 * (bins[i] + bins[i + 1]),
            "speed_bin_low_rpm": bins[i],
            "speed_bin_high_rpm": bins[i + 1],
            "torque_run_value_Nm": median if use_median else mean,
            "torque_run_mean_Nm": mean,
            "torque_run_median_Nm": median,
            "torque_run_std_Nm": float(np.nanstd(torque_bin, ddof=1)) if n > 1 else 0.0,
            "torque_run_min_Nm": float(np.nanmin(torque_bin)),
            "torque_run_max_Nm": float(np.nanmax(torque_bin)),
            "torque_run_iqr_Nm": iqr(torque_bin),
            "sample_count": n,
        })

    return pd.DataFrame(rows)


def process_one_run(job: dict, args) -> tuple[pd.DataFrame, dict]:
    path = job["path"]
    strategy = job["strategy"]
    run_index = job["run_index"]

    raw_df = read_csv_checked(path)
    has_js = detect_joulescope_status(raw_df)
    filtered_df = filter_torque_speed_data(
        df=raw_df,
        use_ramp_only=not args.include_ramp_down,
        min_speed_rpm=args.min_speed_rpm,
        max_speed_rpm=args.max_speed_rpm,
        torque_abs=not args.signed_torque,
        enable_spike_rejection=not args.no_spike_rejection,
        max_torque_slew_mnm_s=args.max_torque_slew_mnm_s,
        hampel_window_s=args.hampel_window_s,
        hampel_n_sigma=args.hampel_n_sigma,
        mean_window_s=args.mean_window_s,
    )
    binned = bin_one_run(filtered_df, args.bin_width_rpm, args.min_samples_per_bin, use_median=not args.use_bin_mean)

    if not binned.empty:
        binned.insert(0, "run_id", f"{strategy}_run{run_index}")
        binned.insert(0, "run_index", run_index)
        binned.insert(0, "source_file", str(path))
        binned.insert(0, "strategy", strategy)

    rejected = int((filtered_df["torque_rejected_flag"] > 0).sum()) if not filtered_df.empty else 0
    rejected_percent = 100.0 * rejected / max(1, len(filtered_df))

    if "torque_sensor_tare_V" in raw_df.columns:
        tare = pd.to_numeric(raw_df["torque_sensor_tare_V"], errors="coerce")
        tare_v = float(np.nanmedian(tare)) if np.isfinite(tare).any() else np.nan
    else:
        tare_v = np.nan

    final_status = np.nan
    if "experiment_status" in raw_df.columns:
        status = pd.to_numeric(raw_df["experiment_status"], errors="coerce")
        if np.isfinite(status).any():
            final_status = int(round(float(status.dropna().iloc[-1])))

    fault_code = np.nan
    if "fault_code" in raw_df.columns:
        fault = pd.to_numeric(raw_df["fault_code"], errors="coerce")
        if np.isfinite(fault).any():
            fault_code = int(round(float(fault.dropna().iloc[-1])))

    summary = {
        "strategy": strategy,
        "run_index": run_index,
        "source_file": str(path),
        "raw_rows": int(len(raw_df)),
        "filtered_rows_used": int(len(filtered_df)),
        "binned_points": int(len(binned)),
        "rejected_samples": rejected,
        "rejected_percent": rejected_percent,
        "joulescope_present": bool(has_js),
        "labjack_tare_voltage_V": tare_v,
        "final_status": final_status,
        "fault_code": fault_code,
    }

    return binned, summary


