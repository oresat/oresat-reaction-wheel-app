"""
TorqueSpeedResults.py

One-stop torque-speed processing, aggregation, and plotting script for the
OreSat reaction wheel thesis tests.

Feed this script one or more raw TorqueSpeedTest CSVs for each commutation
method. It performs the complete processing pipeline, aggregates repeated runs,
writes processed CSVs, and generates thesis-ready figures.

Inputs:
    Raw CSVs generated by TorqueSpeedTest.py or TorqueSpeedTest_no_joulescope.py

Outputs in --outdir, default "Figures":
    torque_speed_curves.png/.pdf
    torque_speed_normalized.png/.pdf
    torque_speed_aggregate_all.csv
    torque_speed_aggregate_<strategy>.csv
    torque_speed_aggregate_runs.csv
    torque_speed_aggregate_summary.csv
    torque_speed_plot_data.csv
    torque_speed_plot_summary.csv
    torque_speed_processing_settings.csv

Processing pipeline:
    Per run:
        raw tared torque_Nm
        -> optional ramp-only extraction
        -> invalid sample removal
        -> slew-rate spike rejection
        -> Hampel outlier rejection
        -> centered rolling mean
        -> RPM binning
        -> per-run median/mean torque per RPM bin

    Across repeated runs:
        per-run binned values
        -> group by strategy and RPM bin
        -> compute mean, median, std, min, max, IQR, run count

    Final curve:
        aggregate binned curve
        -> optional rolling smoothing across neighboring RPM bins
        -> plot final torque-speed figures

Commands:
    python TorqueSpeedTest\TorqueSpeedResults.py --signed-torque --foc TorqueSpeedTest\V2\torque_speed_foc_raw.csv TorqueSpeedTest\V2\torque_speed_foc1_raw.csv TorqueSpeedTest\V2\torque_speed_foc2_raw.csv

    python TorqueSpeedTest\TorqueSpeedResults.py --signed-torque --trap trap1.csv trap2.csv --sine sine1.csv sine2.csv --foc foc1.csv foc2.csv

Important flags:
    --signed-torque
        Preserve signed torque. If omitted, uses absolute torque magnitude.

    --bin-width-rpm
        Per-run RPM bin width. Default: DEFAULT_BIN_WIDTH_RPM

    --max-torque-slew-mnm-s
        Maximum physically plausible torque slew rate. Default: DEFAULT_MAX_TORQUE_SLEW_MNM_S

    --hampel-window-s, --hampel-n-sigma
        Hampel outlier rejection controls.

    --mean-window-s
        Time-domain rolling mean after spike rejection.

    --final-bin-smooth-window
        Final smoothing across aggregate RPM bins.

    --no-show-std
        Disable the default +/- one standard deviation bands.

    --skip-normalized
        Skip normalized torque-speed plot.

Default values are set directly below.
"""

