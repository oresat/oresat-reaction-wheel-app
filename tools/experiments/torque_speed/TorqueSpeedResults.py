def make_plot_summary(plot_df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for strategy, g in iter_strategy_groups(plot_df):
        torque = g["torque_plot_Nm"].to_numpy(dtype=float)
        speed = g["speed_bin_center_rpm"].to_numpy(dtype=float)
        run_count = np.nan
        if "run_count" in g.columns:
            s = pd.to_numeric(g["run_count"], errors="coerce")
            if np.isfinite(s).any():
                run_count = int(np.nanmax(s))
        sample_count = np.nan
        if "total_sample_count" in g.columns:
            s = pd.to_numeric(g["total_sample_count"], errors="coerce")
            if np.isfinite(s).any():
                sample_count = int(np.nansum(s))
        rows.append({
            "strategy": strategy,
            "points": int(len(g)),
            "run_count_max": run_count,
            "total_sample_count": sample_count,
            "min_speed_rpm": float(np.nanmin(speed)),
            "max_speed_rpm": float(np.nanmax(speed)),
            "min_torque_Nm": float(np.nanmin(torque)),
            "max_torque_Nm": float(np.nanmax(torque)),
            "mean_torque_Nm": float(np.nanmean(torque)),
            "median_torque_Nm": float(np.nanmedian(torque)),
            "peak_abs_torque_Nm": float(np.nanmax(np.abs(torque))),
        })
    return pd.DataFrame(rows)


