def read_csv_checked(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)

    required = ["host_time_s", "torque_Nm"]
    for column in required:
        if column not in df.columns:
            raise ValueError(f"{path} is missing required column: {column}")

    if "torque_speed_abs_rpm" not in df.columns:
        if "omega_rpm" not in df.columns:
            raise ValueError(f"{path} is missing torque_speed_abs_rpm and omega_rpm.")
        df["torque_speed_abs_rpm"] = np.abs(pd.to_numeric(df["omega_rpm"], errors="coerce"))

    df = df.copy()
    numeric_columns = [
        "host_time_s", "torque_Nm", "torque_speed_abs_rpm", "torque_speed_signed_rpm",
        "omega_rpm", "speed_command_rpm", "test_state", "experiment_status", "fault_code", "torque_sensor_V",
        "torque_sensor_tare_V", "torque_sensor_delta_V", "js_voltage_V", "js_current_A",
        "js_power_W",
    ]

    for column in numeric_columns:
        if column in df.columns:
            df[column] = pd.to_numeric(df[column], errors="coerce")

    if "torque_speed_signed_rpm" not in df.columns:
        if "omega_rpm" in df.columns:
            df["torque_speed_signed_rpm"] = pd.to_numeric(df["omega_rpm"], errors="coerce")
        else:
            df["torque_speed_signed_rpm"] = df["torque_speed_abs_rpm"]

    return df


def collect_inputs(args) -> list[dict]:
    jobs = []
    for strategy, attr in STRATEGY_INPUTS.items():
        paths = getattr(args, attr)
        if not paths:
            continue
        for run_index, path_str in enumerate(paths, start=1):
            jobs.append({"strategy": strategy, "run_index": run_index, "path": Path(path_str)})

    if not jobs:
        raise ValueError("No input CSV files provided. Pass at least one of --trap, --sine, or --foc.")

    return jobs


def detect_joulescope_status(df: pd.DataFrame) -> bool:
    required = ["js_voltage_V", "js_current_A", "js_power_W"]
    if not all(column in df.columns for column in required):
        return False

    values = [pd.to_numeric(df[column], errors="coerce") for column in required]
    all_values = pd.concat(values, ignore_index=True)
    all_values = all_values[np.isfinite(all_values)]

    if len(all_values) == 0:
        return False

    return bool(np.nanmax(np.abs(all_values.to_numpy(dtype=float))) > 1.0e-12)


