def setup_axes(title: str, xlabel: str, ylabel: str):
    fig, ax = plt.subplots(figsize=(7.0, 4.2))
    ax.set_title(title)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.grid(True, alpha=0.3)
    return fig, ax


def save_figure(fig, outdir: Path, stem: str):
    outdir.mkdir(parents=True, exist_ok=True)
    png = outdir / f"{stem}.png"
    pdf = outdir / f"{stem}.pdf"
    fig.tight_layout()
    fig.savefig(png, dpi=300)
    fig.savefig(pdf)
    plt.close(fig)
    print(f"[FIG] {png}")
    print(f"[FIG] {pdf}")


def iter_strategy_groups(df: pd.DataFrame):
    available = list(df["strategy"].dropna().unique())
    ordered = [s for s in STRATEGY_ORDER if s in available]
    ordered += [s for s in available if s not in ordered]
    for strategy in ordered:
        g = df[df["strategy"] == strategy].sort_values("speed_bin_center_rpm")
        if not g.empty:
            yield strategy, g


def prepare_plot_data(aggregate: pd.DataFrame, plot_column: str) -> pd.DataFrame:
    if plot_column not in aggregate.columns:
        raise ValueError(f"Requested plot column does not exist: {plot_column}")
    out = aggregate.copy()
    out[plot_column] = pd.to_numeric(out[plot_column], errors="coerce")
    out = out[np.isfinite(out[plot_column])]
    out["torque_plot_Nm"] = out[plot_column]
    return out.sort_values(["strategy", "speed_bin_center_rpm"]).reset_index(drop=True)


def plot_measured_torque_speed(df: pd.DataFrame, outdir: Path, show_std: bool, signed_torque: bool):
    # Values are stored in N·m, but the measured torque levels are most readable
    # and consistent with the thesis tables when displayed in mN·m.
    ylabel = "Reaction Torque (mN·m)" if signed_torque else "Reaction Torque Magnitude (mN·m)"
    fig, ax = setup_axes("Measured Torque-Speed Characteristic", "Wheel Speed (RPM)", ylabel)

    for strategy, g in iter_strategy_groups(df):
        x = g["speed_bin_center_rpm"].to_numpy(dtype=float)
        y = 1000.0 * g["torque_plot_Nm"].to_numpy(dtype=float)
        color = STRATEGY_COLORS[strategy]

        ax.plot(
            x,
            y,
            linewidth=2.2,
            marker="o",
            markersize=3.0,
            label=strategy,
            color=color,
        )

        if show_std and "torque_std_Nm" in g.columns:
            std = 1000.0 * pd.to_numeric(
                g["torque_std_Nm"], errors="coerce"
            ).to_numpy(dtype=float)
            ax.fill_between(
                x,
                y - std,
                y + std,
                color=color,
                alpha=0.15,
                linewidth=0.0,
            )

    if signed_torque:
        ax.axhline(0.0, linewidth=0.8, alpha=0.5)

    ax.legend(title="Commutation Strategy")
    save_figure(fig, outdir, "torque_speed_curves")


def plot_normalized_torque_speed(df: pd.DataFrame, outdir: Path, show_std: bool, signed_torque: bool):
    ylabel = "Normalized Reaction Torque" if signed_torque else "Normalized Torque Magnitude"
    fig, ax = setup_axes("Normalized Torque-Speed Characteristic", "Wheel Speed (RPM)", ylabel)

    for strategy, g in iter_strategy_groups(df):
        x = g["speed_bin_center_rpm"].to_numpy(dtype=float)
        y = g["torque_plot_Nm"].to_numpy(dtype=float)
        peak = np.nanmax(np.abs(y))

        if not np.isfinite(peak) or peak <= 0.0:
            continue

        color = STRATEGY_COLORS[strategy]
        y_normalized = y / peak

        ax.plot(
            x,
            y_normalized,
            linewidth=2.2,
            marker="o",
            markersize=3.0,
            label=strategy,
            color=color,
        )

        if show_std and "torque_std_Nm" in g.columns:
            std = pd.to_numeric(
                g["torque_std_Nm"], errors="coerce"
            ).to_numpy(dtype=float) / peak
            ax.fill_between(
                x,
                y_normalized - std,
                y_normalized + std,
                color=color,
                alpha=0.15,
                linewidth=0.0,
            )

    if signed_torque:
        ax.axhline(0.0, linewidth=0.8, alpha=0.5)

    ax.legend(title="Commutation Strategy")
    save_figure(fig, outdir, "torque_speed_normalized")


